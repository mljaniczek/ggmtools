#' TCGA breast cancer PI3K pathway expression, Normal vs Tumor
#'
#' RNA-seq expression of the 28 PI3K-pathway genes (Sanchez-Vega et al.
#' 2018) in 100 normal breast tissue samples and 100 primary breast tumours
#' from The Cancer Genome Atlas (TCGA) BRCA cohort. This is the dataset of
#' the TCGA example in the DiNA simulation paper. It is shipped here so that
#' \pkg{spikeyglass}, \pkg{multiGGMr} and other packages use one identical
#' object.
#'
#' @format A named list of two numeric matrices, \code{Normal} and
#'   \code{Tumor}, each 100 samples x 28 genes, with HGNC gene symbols as
#'   column names (in the same order in both). The attribute \code{"genes"}
#'   is a data frame with the columns \code{Gene}, \code{og_tsg} (oncogene /
#'   tumour suppressor / other, from Sanchez-Vega et al.) and \code{pathway}.
#'
#' @details
#' Built by \code{data-raw/brca_pi3k.R} in the package sources:
#' \enumerate{
#'   \item curatedTCGAData 2.1.1, BRCA RNASeqGene assay
#'     (\code{BRCA_RNASeqGene-20160128}, raw counts). Tumour = TCGA sample
#'     type 01, Normal = 11; the 3 metastatic samples are dropped.
#'   \item Genes with a count of at least 10 in fewer than 20\% of samples are
#'     dropped.
#'   \item DESeq2 variance-stabilising transformation
#'     (\code{vst(blind = FALSE)}, design \code{~ sample_type}).
#'   \item Each gene is z-scored across \emph{all} Normal and Tumour samples
#'     together. The groups are therefore \strong{not} standardised
#'     separately: within group, the Normal genes have standard deviations of
#'     about 0.7 and the Tumour genes about 1. Standardise within group (e.g.
#'     \code{spikeyglass::ssjgl(standardize = TRUE)}) if your method needs
#'     it.
#'   \item Normal samples, and tumours of patients without a paired normal
#'     sample, are kept, so the two groups come from different patients.
#'   \item The PI3K-pathway genes of Sanchez-Vega et al. (2018) are kept (28 of
#'     29 pass the filters).
#'   \item The first 100 tumours (in the order produced by the pipeline, not a
#'     random sample) are kept to balance the 100 normals.
#' }
#' Sample identifiers are not included.
#'
#' @source The Cancer Genome Atlas, via the Bioconductor package
#'   curatedTCGAData (Ramos et al. 2020). The results here are in whole or in
#'   part based upon data generated by the TCGA Research Network:
#'   \url{https://www.cancer.gov/tcga}.
#'
#' @references
#' Cancer Genome Atlas Network (2012). Comprehensive molecular portraits of
#' human breast tumours. \emph{Nature}, 490, 61--70.
#' \doi{10.1038/nature11412}
#'
#' Sanchez-Vega, F., Mina, M., Armenia, J., et al. (2018). Oncogenic
#' signaling pathways in The Cancer Genome Atlas. \emph{Cell}, 173(2),
#' 321--337. \doi{10.1016/j.cell.2018.03.035}
#'
#' Ramos, M., Geistlinger, L., Oh, S., et al. (2020). Multiomic integration
#' of public oncology databases in Bioconductor. \emph{JCO Clinical Cancer
#' Informatics}, 4, 958--971. \doi{10.1200/CCI.19.00119}
#'
#' Love, M. I., Huber, W. and Anders, S. (2014). Moderated estimation of fold
#' change and dispersion for RNA-seq data with DESeq2. \emph{Genome Biology},
#' 15, 550. \doi{10.1186/s13059-014-0550-8}
#'
#' @examples
#' str(brca_pi3k)
#' head(attr(brca_pi3k, "genes"))
#' sapply(brca_pi3k, function(m) round(mean(apply(m, 2, sd)), 2))
